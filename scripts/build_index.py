#!/usr/bin/env python3
"""Rebuild the puzzle tiles in index.html from the puzzle pages.

Each puzzle page (puzzles/<slug>/index.html) is the single source of truth
for its tile on the index:

  title   <h1> (fallbacks: <meta name="puzzle:title">, then <title>)
  desc    <p class="rule"> (fallback: <meta name="puzzle:rule">)

JS-rendered pages (emptying-poles) keep title/rule in those metas and render
them from there, so the metas stay the single source. Meta content may hold
entity-escaped markup (&lt;em&gt;...) — it is unescaped here.
  tags    <meta name="puzzle:tags" content="a · b">
  emblem  <template class="tile-emblem"> holding the tile SVG

Tile order comes from puzzles/order.txt (one slug per line, '#' comments).
The generated tiles replace whatever sits between the build markers in
index.html. Run from anywhere; paths are repo-relative to this file.

A git pre-commit hook runs this automatically; run by hand after editing
a puzzle's title/rule/tags/emblem to see the index update locally.
"""
import html
import re
import sys
from xml.sax.saxutils import escape as xml_escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "index.html"
ORDER = ROOT / "puzzles" / "order.txt"
MARK_OPEN = "<!-- tiles:generated by scripts/build_index.py; edit the puzzle pages, not this block -->"
MARK_CLOSE = "<!-- /tiles:generated -->"


def fail(msg):
    sys.exit(f"build_index: {msg}")


SITE = "https://jonilaserson.github.io/puzzles/"
SITE_NAME = "Puzzles by Jonathan Laserson"


def plain(text):
    """Tags stripped, entities decoded, whitespace collapsed."""
    text = re.sub(r"<[^>]+>", "", text)
    return re.sub(r"\s+", " ", html.unescape(text)).strip()


def sentence(text):
    """Capitalised, with terminal punctuation (adds a full stop if missing)."""
    text = text.strip()
    if text[-1] not in ".?!":
        text += "."
    return text[0].upper() + text[1:]


def extract(pattern, text, flags=re.S):
    m = re.search(pattern, text, flags)
    return m.group(1).strip() if m else None


def tile_title(page, slug):
    h1 = extract(r"<h1[^>]*>(.*?)</h1>", page)
    if h1 is None:
        meta = extract(r'<meta name="puzzle:title" content="([^"]*)"', page)
        h1 = html.unescape(meta) if meta is not None else None
    if h1 is None:
        h1 = extract(r"<title>(.*?)</title>", page)
    if h1 is None:
        fail(f"{slug}: no <h1>, no <meta name=\"puzzle:title\">, no <title>")
    h1 = re.sub(r"<br\s*/?>", " ", h1)
    h1 = re.sub(r"<[^>]+>", "", h1)  # keep text and entities only
    return re.sub(r"\s+", " ", h1).strip()


def tile_rule(page, slug):
    rule = extract(r'<p class="rule"[^>]*>(.*?)</p>', page)
    if rule is None:
        meta = extract(r'<meta name="puzzle:rule" content="([^"]*)"', page)
        rule = html.unescape(meta) if meta is not None else None
    if rule is None:
        fail(f"{slug}: no <p class=\"rule\"> and no <meta name=\"puzzle:rule\">")
    return re.sub(r"\s+", " ", rule).strip()


def tile_original(page):
    """<meta name="puzzle:original" content="..."> marks a page whose proof is
    the author's own; the content becomes the badge's tooltip. None if absent."""
    return extract(r'<meta name="puzzle:original" content="([^"]*)"', page)


def tile_badge(page):
    why = tile_original(page)
    return f'<br><span class="orig" title="{why}">original proof</span>' if why else ""


def tile_tags(page, slug):
    tags = extract(r'<meta name="puzzle:tags" content="([^"]*)"', page)
    if tags is None:
        fail(f"{slug}: missing <meta name=\"puzzle:tags\" content=\"a · b\">")
    parts = [p.strip() for p in tags.split("·") if p.strip()]
    if not parts:
        fail(f"{slug}: empty puzzle:tags")
    return "<br>".join(parts)


def tile_emblem(page, slug):
    svg = extract(r'<template class="tile-emblem">(.*?)</template>', page)
    if svg is None:
        fail(f"{slug}: missing <template class=\"tile-emblem\"> with the tile SVG")
    return "\n".join("            " + ln.strip() for ln in svg.splitlines() if ln.strip())


# --- share tags -----------------------------------------------------------
# Every puzzle page gets a generated <head> block (description, canonical,
# Open Graph, Twitter summary card) derived from its own title and rule, so a
# shared link previews properly and never drifts from the page.
SHARE_OPEN = "<!-- share:generated by scripts/build_index.py from the title and rule; do not hand-edit -->"
SHARE_CLOSE = "<!-- /share:generated -->"


def share_block(page, slug):
    title = plain(tile_title(page, slug))
    desc = (f"{sentence(title)} {sentence(plain(tile_rule(page, slug)))} "
            "A small mathematical puzzle with a playable simulator and a proof.")
    url = f"{SITE}puzzles/{slug}/"
    esc = lambda t: html.escape(t, quote=True)
    return "\n".join([
        SHARE_OPEN,
        f'<meta name="description" content="{esc(desc)}">',
        f'<link rel="canonical" href="{url}">',
        '<meta property="og:type" content="website">',
        f'<meta property="og:site_name" content="{esc(SITE_NAME)}">',
        f'<meta property="og:title" content="{esc(title)}">',
        f'<meta property="og:description" content="{esc(desc)}">',
        f'<meta property="og:url" content="{url}">',
        '<meta name="twitter:card" content="summary">',
        SHARE_CLOSE,
    ])


def write_share(slug):
    path = ROOT / "puzzles" / slug / "index.html"
    page = path.read_text(encoding="utf-8")
    block = share_block(page, slug)
    pattern = re.compile(re.escape(SHARE_OPEN) + r".*?" + re.escape(SHARE_CLOSE), re.S)
    if pattern.search(page):
        rebuilt = pattern.sub(lambda m: block, page, count=1)
    else:
        m = re.search(r"</title>[ \t]*\n", page)
        if not m:
            fail(f"{slug}: cannot place share tags (no </title> line)")
        rebuilt = page[:m.end()] + block + "\n" + page[m.end():]
    if rebuilt != page:
        path.write_text(rebuilt, encoding="utf-8")
        return True
    return False


def build_tile(slug, num):
    path = ROOT / "puzzles" / slug / "index.html"
    if not path.exists():
        fail(f"{slug}: {path} not found (fix puzzles/order.txt?)")
    page = path.read_text(encoding="utf-8")
    return f"""      <li data-puzzle="{slug}">
        <a href="puzzles/{slug}/index.html">
          <span class="num">{num:02d}</span>
          <span class="thumb" aria-hidden="true">
{tile_emblem(page, slug)}
          </span>
          <span class="body">
            <span class="title">{tile_title(page, slug)}</span>
            <span class="desc">{tile_rule(page, slug)}</span>
          </span>
          <span class="tag">{tile_tags(page, slug)}{tile_badge(page)}</span>
        </a>
      </li>"""


# --- Atom feed ------------------------------------------------------------
# feed.xml lists the puzzles newest first. A puzzle's entry date is its
# <meta name="puzzle:date" content="YYYY-MM-DD"> (the day it was added). The
# feed's own <updated> is the newest entry date, so rebuilding is idempotent.
FEED = ROOT / "feed.xml"


def feed_entry(slug, order):
    page = (ROOT / "puzzles" / slug / "index.html").read_text(encoding="utf-8")
    day = extract(r'<meta name="puzzle:date" content="(\d{4}-\d{2}-\d{2})"', page)
    if day is None:
        fail(f"{slug}: missing <meta name=\"puzzle:date\" content=\"YYYY-MM-DD\">")
    return (day, order, slug,
            plain(tile_title(page, slug)), sentence(plain(tile_rule(page, slug))))


def write_feed(slugs):
    entries = sorted((feed_entry(s, i) for i, s in enumerate(slugs)), reverse=True)
    x = xml_escape
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<feed xmlns="http://www.w3.org/2005/Atom">',
           f"  <title>{x(SITE_NAME)}</title>",
           "  <subtitle>Small mathematical puzzles, with proofs and playable simulators.</subtitle>",
           f'  <link href="{SITE}"/>',
           f'  <link rel="self" type="application/atom+xml" href="{SITE}feed.xml"/>',
           f"  <id>{SITE}</id>",
           f"  <updated>{entries[0][0]}T00:00:00Z</updated>",
           "  <author><name>Jonathan Laserson</name></author>"]
    for day, _, slug, title, rule in entries:
        url = f"{SITE}puzzles/{slug}/"
        out += ["  <entry>",
                f"    <title>{x(title)}</title>",
                f'    <link href="{url}"/>',
                f"    <id>{url}</id>",
                f"    <updated>{day}T00:00:00Z</updated>",
                f"    <summary>{x(rule)}</summary>",
                "  </entry>"]
    out.append("</feed>")
    text = "\n".join(out) + "\n"
    old = FEED.read_text(encoding="utf-8") if FEED.exists() else None
    if text != old:
        FEED.write_text(text, encoding="utf-8")
        print(f"build_index: wrote feed.xml ({len(entries)} entries)")


def main():
    slugs = [ln.strip() for ln in ORDER.read_text(encoding="utf-8").splitlines()
             if ln.strip() and not ln.strip().startswith("#")]
    if not slugs:
        fail(f"{ORDER} lists no puzzles")

    write_feed(slugs)

    tiles = "\n".join(build_tile(s, i) for i, s in enumerate(slugs, 1))
    index = INDEX.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(MARK_OPEN) + r".*?" + re.escape(MARK_CLOSE), re.S)
    if not pattern.search(index):
        fail(f"index.html is missing the tile markers ({MARK_OPEN})")
    rebuilt = pattern.sub(MARK_OPEN + "\n" + tiles + "\n      " + MARK_CLOSE, index)

    if rebuilt != index:
        INDEX.write_text(rebuilt, encoding="utf-8")
        print(f"build_index: rebuilt {len(slugs)} tiles -> index.html")
    else:
        print(f"build_index: index.html already up to date ({len(slugs)} tiles)")

    shared = [slug for slug in slugs if write_share(slug)]
    if shared:
        print(f"build_index: refreshed share tags in {len(shared)} puzzle pages")


if __name__ == "__main__":
    main()
